#!/usr/bin/env python3
"""Regenerate src/cardigann_exec/single_byte.rs from CPython's code-page codecs.

Bytes 0x00-0x7F are ASCII in every admitted code page. For 0x80-0xFF, CPython's
tables (from the Unicode Consortium vendor mappings) give the defined code points.
Positions CPython leaves undefined are decoded by Windows and .NET's
CodePagesEncodingProvider as the C1 control with the same value. That is the
Microsoft best-fit table's MBTABLE entry and is reproduced here.
Usage: python3 tools/gen_single_byte_tables.py > src/cardigann_exec/single_byte.rs
"""
import sys

PAGES = [
    ("WINDOWS_1250", "cp1250", "windows-1250"),
    ("WINDOWS_1251", "cp1251", "windows-1251"),
    ("WINDOWS_1252", "cp1252", "windows-1252"),
    ("WINDOWS_1256", "cp1256", "windows-1256"),
    ("ISO_8859_2", "iso8859_2", "ISO-8859-2"),
]

out = sys.stdout
out.write("//! Generated by tools/gen_single_byte_tables.py; do not edit by hand.\n")
out.write("//! High halves (0x80..=0xFF) of the admitted single-byte code pages.\n")
for const, codec, label in PAGES:
    chars = []
    for b in range(0x80, 0x100):
        c = bytes([b]).decode(codec, errors="replace")
        chars.append(chr(b) if c == "�" else c)
    assert len(set(chars)) == 128, label
    out.write(f"/// {label}\npub(super) static {const}: [char; 128] = [\n")
    for i in range(0, 128, 8):
        row = ", ".join(f"'\\u{{{ord(c):04x}}}'" for c in chars[i : i + 8])
        out.write(f"    {row},\n")
    out.write("];\n")
