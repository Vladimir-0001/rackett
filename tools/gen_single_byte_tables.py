#!/usr/bin/env python3
"""Regenerate src/cardigann_exec/single_byte.rs from .NET 9's own code-page data.

The tables come from the two files .NET 9 itself uses (dotnet/runtime tag v9.0.0):

- src/libraries/System.Text.Encoding.CodePages/src/Data/codepages.nlp, read by
  CodePagesEncodingProvider. Each SBCS page has a 256-entry byte->char table, a
  byte->char best-fit list and a Unicode->byte best-fit list. The layout follows
  BaseCodePageEncoding.cs and SBCSCodePageEncoding.cs (LoadManagedCodePage and
  ReadBestFitTable).
- src/libraries/System.Private.CoreLib/src/System/Text/EncoderLatin1BestFitFallback.Data.cs,
  the encoder fallback of Latin1Encoding ("iso-8859-1").

Decoding uses the byte->char table after the byte best-fit list is applied, as
SBCSCodePageEncoding.GetChars does under its default InternalDecoderBestFitFallback.
The output is checked against CPython's code-page codecs, which follow the Unicode
MICSFT/VENDORS mappings, for every byte that CPython defines. Bytes CPython leaves
undefined take .NET's value: a C1 control, or a private-use code point in
windows-1255 and windows-874, as in Microsoft's bestfit1255.txt/bestfit874.txt
MBTABLE. Encoder best-fit lists map a character with no exact byte to its best-fit
byte. .NET falls back to '?' for characters outside these lists.

Usage:
  python3 -I tools/gen_single_byte_tables.py codepages.nlp \
      EncoderLatin1BestFitFallback.Data.cs > src/cardigann_exec/single_byte.rs
"""
import re
import struct
import sys

# (Rust constant, .NET code page, CPython codec, label)
PAGES = [
    ("WINDOWS_1250", 1250, "cp1250", "windows-1250"),
    ("WINDOWS_1251", 1251, "cp1251", "windows-1251"),
    ("WINDOWS_1252", 1252, "cp1252", "windows-1252"),
    ("WINDOWS_1255", 1255, "cp1255", "windows-1255"),
    ("WINDOWS_1256", 1256, "cp1256", "windows-1256"),
    ("WINDOWS_874", 874, "cp874", "windows-874"),
    ("ISO_8859_2", 28592, "iso8859_2", "ISO-8859-2"),
]


def u16(data, offset):
    return struct.unpack_from("<H", data, offset)[0]


def code_page(data, cp):
    """Return (bytes->chars after best fit, [(char, byte)] encoder best fit)."""
    count = struct.unpack_from("<h", data, 0x28)[0]
    for i in range(count):
        entry = 44 + i * 40  # CODEPAGE_DATA_FILE_HEADER_SIZE, sizeof(CodePageIndex)
        index_cp, _, offset = struct.unpack_from("<HhI", data, entry + 32)
        if index_cp == cp:
            break
    else:
        raise SystemExit(f"code page {cp} missing")
    header_cp, byte_count = struct.unpack_from("<Hh", data, offset + 0x28)
    assert header_cp == cp and byte_count == 1, cp
    first = offset + 48  # CODEPAGE_HEADER_SIZE
    chars = list(struct.unpack_from("<256H", data, first))
    assert 0xFFFD not in chars and all(c or b == 0 for b, c in enumerate(chars)), cp
    p = first + 512
    while u16(data, p) != 0:  # bytes->Unicode best fit, (byte, char) until byte 0
        chars[u16(data, p)] = u16(data, p + 2)
        p += 4
    p += 2
    position = u16(data, p)
    p += 2
    best_fit = []
    while position < 0x10000:  # Unicode->bytes best fit, run-length coded
        byte = data[p]
        p += 1
        if byte == 1:
            position = u16(data, p)
            p += 2
        elif 0 < byte < 0x20 and byte != 0x1E:
            position += byte
        else:
            if byte == 0x1E:
                byte = data[p]
                p += 1
            if byte > 0:
                best_fit.append((position, byte))
            position += 1
    return chars, best_fit


def latin1_best_fit(source):
    """Uncommented (char)0x...., (char)0x.... pairs of ArrayCharBestFit."""
    pairs = []
    for line in source.splitlines():
        if line.lstrip().startswith("//"):
            continue
        m = re.match(r"\s*\(char\)0x([0-9a-fA-F]{4}), \(char\)0x([0-9a-fA-F]{4}),?", line)
        if m:
            pairs.append((int(m[1], 16), int(m[2], 16)))
    return pairs


def emit_best_fit(out, const, label, pairs):
    assert pairs == sorted(pairs) and len({c for c, _ in pairs}) == len(pairs), label
    n = len(pairs)
    out.write(f"/// {label}: characters with an encoder best fit, sorted\n")
    out.write(f"pub(super) static {const}_BEST_FIT: [char; {n}] = [\n")
    for i in range(0, n, 8):
        row = ", ".join(f"'\\u{{{c:04x}}}'" for c, _ in pairs[i : i + 8])
        out.write(f"    {row},\n")
    out.write("];\n")
    out.write(f"/// {label}: best-fit byte of each `{const}_BEST_FIT` character\n")
    out.write(f"pub(super) static {const}_BEST_FIT_BYTES: [u8; {n}] = [\n")
    for i in range(0, n, 16):
        row = ", ".join(f"0x{b:02x}" for _, b in pairs[i : i + 16])
        out.write(f"    {row},\n")
    out.write("];\n")


def main():
    nlp = open(sys.argv[1], "rb").read()
    latin1 = open(sys.argv[2], encoding="utf-8").read()
    out = sys.stdout
    out.write("//! Generated by tools/gen_single_byte_tables.py; do not edit by hand.\n")
    out.write("//! .NET 9 codepages.nlp and Latin1Encoding best-fit data (dotnet/runtime v9.0.0):\n")
    out.write("//! high halves (0x80..=0xFF) and encoder best-fit lists of the admitted pages.\n")
    for const, cp, codec, label in PAGES:
        chars, best_fit = code_page(nlp, cp)
        assert chars[:128] == list(range(128)), label
        assert len(set(chars)) == 256, label
        for b in range(0x80, 0x100):
            try:
                expected = ord(bytes([b]).decode(codec))
            except UnicodeDecodeError:
                continue
            assert chars[b] == expected, (label, hex(b))
        out.write(f"/// {label}\npub(super) static {const}: [char; 128] = [\n")
        for i in range(0x80, 0x100, 8):
            row = ", ".join(f"'\\u{{{c:04x}}}'" for c in chars[i : i + 8])
            out.write(f"    {row},\n")
        out.write("];\n")
        emit_best_fit(out, const, label, best_fit)
    pairs = latin1_best_fit(latin1)
    assert all(c > 0xFF and b < 0x100 for c, b in pairs)
    emit_best_fit(out, "LATIN1", "iso-8859-1", pairs)


main()
